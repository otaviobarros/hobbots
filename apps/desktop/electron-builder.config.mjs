import { electronFuses } from "./scripts/electron-fuses.ts";
import { removeSharedWrite } from "./scripts/linux-permissions.ts";
import { ENGINE_RESOURCE, MEMORY_ENGINE_SIGN_IGNORE, prepareMemoryEngine } from "./scripts/memory-engine.ts";

/**
 * The memory engine for the platform and architecture being built, as `fetch-engine` checked it
 * (ADR 028), with its license. Its checksum is written by `afterPack`, after it is signed on macOS.
 */
const memoryEngine = (platform) => ({
  from: `../../packages/memory/engine/${platform}-\${arch}`,
  to: ENGINE_RESOURCE,
  filter: ["ai-memory", "LICENSE"],
});

/** Every installer's file name, such as Hobbots-1.2.3-arm64.dmg, Hobbots-1.2.3-amd64.deb or Hobbots-1.2.3-x86_64.rpm. */
const ARTIFACT_NAME = "${productName}-${version}-${arch}.${ext}";

/** What the tool sandbox, sandbox-runtime, needs on Linux (ADR 014); the same names on Debian and Fedora. */
const SANDBOX_DEPENDENCIES = ["bubblewrap", "socat", "ripgrep"];

/** The defaults electron-builder 26 declares for an Electron app, which `depends` replaces. */
const ELECTRON_DEB_DEPENDS = [
  "libgtk-3-0",
  "libnotify4",
  "libnss3",
  "libxss1",
  "libxtst6",
  "xdg-utils",
  "libatspi2.0-0",
  "libuuid1",
  "libsecret-1-0",
];
const ELECTRON_RPM_DEPENDS = [
  "gtk3",
  "libnotify",
  "nss",
  "libXScrnSaver",
  "(libXtst or libXtst6)",
  "xdg-utils",
  "at-spi2-core",
  "(libuuid or libuuid1)",
];

/** @type {import("electron-builder").Configuration} */
export default {
  // CFBundleIdentifier. The data folder follows the product name, not this, so it is unaffected.
  appId: "ai.hobbots.app",
  productName: "Hobbots",
  // Shown by Finder's Get Info and the About panel; the version comes from package.json.
  copyright: "Copyright © 2026 The Hobbots contributors. Licensed under the Apache License 2.0.",
  // Outside dist/ and out/, which Turborepo caches as build outputs.
  directories: { output: "release", buildResources: "resources" },
  // Everything the main process needs is bundled into out/ by electron-vite. Claude Code is not
  // shipped: the server runs the one installed on the host.
  files: ["out/**", "package.json"],
  npmRebuild: false,
  // The release workflow attaches the installers to the draft release itself, and the app has no
  // auto-updater, so no update feed (app-update.yml, latest-linux.yml) is written. Without this a
  // GH_TOKEN in the environment makes electron-builder look for one and fail on Linux.
  publish: null,
  // Turns off what lets another program run code as the app, such as NODE_OPTIONS and --inspect, and
  // loads only the app's own checked archive (STD-DESKTOP-007). check-fuses.ts reads them back.
  electronFuses,
  extraResources: [
    { from: "../web/dist", to: "web" },
    { from: "../../LICENSE", to: "LICENSE" },
  ],
  afterPack: async (context) => {
    await prepareMemoryEngine(context);
    if (context.electronPlatformName === "linux") await removeSharedWrite(context.appOutDir);
  },
  mac: {
    // One installer per architecture rather than a universal build: there are no native modules,
    // so universal would work, but it carries both Electron frameworks and roughly doubles the
    // download for everyone.
    target: [{ target: "dmg", arch: ["arm64", "x64"] }],
    extraResources: [memoryEngine("darwin")],
    category: "public.app-category.productivity",
    // The chief of the hobs, generated by scripts/app-icon.ts.
    icon: "resources/icon.icns",
    // Ad-hoc signed, with no certificate: keeps the bundle's seal valid so macOS offers to open
    // a downloaded copy rather than calling it damaged. Real signing and notarization come later.
    identity: "-",
    hardenedRuntime: false,
    // The memory engine is signed by afterPack, before its checksum is written.
    signIgnore: [MEMORY_ENGINE_SIGN_IGNORE],
  },
  dmg: {
    artifactName: ARTIFACT_NAME,
    // The window shows the app beside an Applications shortcut to drag it onto.
    window: { width: 540, height: 380 },
    contents: [
      { x: 130, y: 220, type: "file" },
      { x: 410, y: 220, type: "link", path: "/Applications" },
    ],
  },
  linux: {
    // Ubuntu 24.04 and Debian take the .deb, Fedora the .rpm. Both install scripts set up Chromium's
    // sandbox: an AppArmor profile that allows it user namespaces where AppArmor restricts them
    // (Ubuntu 24.04 and later), and a setuid chrome-sandbox where the kernel has none. An AppImage
    // can do neither, nor install the tool sandbox's dependencies, so it waits.
    target: [
      { target: "deb", arch: ["x64", "arm64"] },
      { target: "rpm", arch: ["x64", "arm64"] },
    ],
    extraResources: [memoryEngine("linux")],
    executableName: "hobbots",
    // The .desktop file is named after `desktopName` in package.json, which Electron also uses as the
    // window's app ID, so the desktop links the running window to the launcher's icon.
    syncDesktopName: true,
    category: "Development",
    // One PNG per size, drawn by scripts/app-icon.ts like icon.icns.
    icon: "resources/icons",
    // The package's summary and description, from the README.
    synopsis: "Little helpers that do your chores while you sleep",
    description: "A personal, local-first, self-hostable workspace for AI agents.",
    maintainer: "Otavio Barros <35647586+otaviobarros@users.noreply.github.com>",
    vendor: "The Hobbots contributors",
  },
  deb: {
    artifactName: ARTIFACT_NAME,
    depends: [...ELECTRON_DEB_DEPENDS, ...SANDBOX_DEPENDENCIES],
    // secret-tool keeps the GitHub Charm's tokens in the Secret Service (ADR 020); without it the hub
    // refuses to keep them, and everything else works.
    recommends: ["libsecret-tools", "libappindicator3-1"],
  },
  rpm: {
    // Lowercase like the .deb, so `dnf remove hobbots` and `apt remove hobbots` match.
    packageName: "hobbots",
    artifactName: ARTIFACT_NAME,
    // On Fedora secret-tool comes with libsecret, which Electron needs anyway.
    depends: [...ELECTRON_RPM_DEPENDS, "libsecret", ...SANDBOX_DEPENDENCIES],
  },
};
