/** The hats a sprite can wear; the art lives with the sprite generator. */
export const RoleHat = Schema.Literals([
  "pointed",
  "wizard",
  "beanie",
  "hood",
  "mushroom",
  "sprout",
  "horned",
  "crown",
]);
