export interface StarterRole {
  readonly id: string;
  readonly family: RoleFamily;
  readonly title: string;
  /** One line for the picker on what a hob in this role does. */
  readonly note: string;
  readonly hat: RoleHat;
  readonly tool: RoleTool;
  readonly sigil: ReadonlyArray<string>;
}

