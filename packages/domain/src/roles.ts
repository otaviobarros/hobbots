/** A starter role id, such as "engineer". */
export const RoleId = Schema.Literals(STARTER_ROLES.map((role) => role.id));
export type RoleId = typeof RoleId.Type;

/** The roles the picker shows first, before the families. */
export const PICKER_FIRST: ReadonlyArray<RoleId> = [
  "assistant",
  "researcher",
  "writer",
  "engineer",
  "exec",
  "analyst",
  "tutor",
  "lifeorg",
];

/** The sigil a custom title gets until the user borrows another one. */
export const DEFAULT_SIGIL: RoleId = "assistant";

const byId: ReadonlyMap<string, StarterRole> = new Map(STARTER_ROLES.map((role) => [role.id, role]));

/** The starter role with this id. */
export const starterRole = (id: RoleId): StarterRole => byId.get(id) as StarterRole;

/** A hob's role fields when it takes a starter role: its title, sigil, hat and tool. */
export const roleFields = (id: RoleId) => {
  const role = starterRole(id);
  return { role: id, roleTitle: role.title, sigil: id, hat: role.hat, tool: role.tool } as const;
};

/**
 * Who the hob is, as the hub tells its runtime at the start of every turn: its name and its role,
 * with the starter role's note. The role is never written into the instructions, so a role change
 * applies from the next turn.
 */
export const hobIdentity = (name: string, role: RoleId | null, roleTitle: string): string =>
  role === null
    ? `You are ${name}, a hob in Hobbots. Your role is ${roleTitle}.`
    : `You are ${name}, a hob in Hobbots. Your role is ${roleTitle}: ${starterRole(role).note.toLowerCase()}`;

/**
 * What the runtime is told before the user's messages, in labeled sections so the model can tell
 * what Hobbots states about the hob from what the user wrote: who the hob is, how it talks when its
 * tone differs from the defaults, then its instructions, last, so the user's own words win.
 */
export const systemInstructions = (
  name: string,
  config: {
    readonly role: RoleId | null;
    readonly roleTitle: string;
    readonly voice: Voice;
    readonly length: ReplyLength;
    readonly instructions: string;
  },
): string => {
  const tone = toneLines(config.voice, config.length);
  const instructions = config.instructions.trim();
  return [
    `## About you\n${hobIdentity(name, config.role, config.roleTitle)}`,
    ...(tone.length === 0 ? [] : [`## How you talk\n${tone.join("\n")}`]),
    ...(instructions === "" ? [] : [`## Your instructions, from the user\n${instructions}`]),
  ].join("\n\n");
};
