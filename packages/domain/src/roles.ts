import { Schema } from "effect";
import { type ReplyLength, toneLines, type Voice } from "./tone.ts";

/**
 * The starter roles a hob can take. A role is a title with a sigil, and the hat and tool
 * its sprite wears. Roles are labels only: they grant no tools, permissions or authority, the
 * Leadership roles included (ADR 005). The set is capped at 60.
 *
 * A sigil is a 10 × 10 grid: "#" is moonlight, "o" is amber and "." is the plate.
 */

export const RoleFamily = Schema.Literals([
  "helpers",
  "leadership",
  "software",
  "business",
  "learning",
  "creative",
  "life",
]);
export type RoleFamily = typeof RoleFamily.Type;

